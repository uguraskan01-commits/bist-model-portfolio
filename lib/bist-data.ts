export function getAllBISTStocks(): BISTStock[] {
  return BIST_TUM_RAW.map((item) => {
    // Endeks kategorisini belirle
    let indexCategory: 'BIST 30' | 'BIST 50' | 'BIST 100' | 'BIST TÜM' = 'BIST TÜM';
    if (BIST_30_SET.has(item.symbol)) {
      indexCategory = 'BIST 30';
    } else if (BIST_50_SET.has(item.symbol)) {
      indexCategory = 'BIST 50';
    } else if (BIST_100_SET.has(item.symbol)) {
      indexCategory = 'BIST 100';
    } else {
      indexCategory = 'BIST TÜM';
    }
    let sectorPeAvg = 10.0;
    if (item.sector === 'Bankacılık') sectorPeAvg = 5.2;
    else if (item.sector === 'Havacılık') sectorPeAvg = 8.5;
    else if (item.sector === 'Enerji') sectorPeAvg = 12.5;
    else if (item.sector === 'Teknoloji & Bilişim') sectorPeAvg = 18.0;
    else if (item.sector === 'Savunma Sanayi') sectorPeAvg = 16.0;
    else if (item.sector === 'Perakende') sectorPeAvg = 14.0;
    else if (item.sector === 'Holding') sectorPeAvg = 7.0;

    const valuationDiscount = +(((sectorPeAvg - item.pe) / sectorPeAvg) * 100).toFixed(1);
    const upsidePotential = +(((item.targetPrice - item.price) / item.price) * 100).toFixed(1);

    const supportLevel = +(item.price * 0.94).toFixed(2);
    const resistanceLevel = +(item.price * 1.08).toFixed(2);
    const stopLossLevel = +(item.price * 0.91).toFixed(2);

    const isBreakout = item.trend === 'GÜÇLÜ YÜKSELİŞ';
    const isNearSupport = item.rsi < 50;

    // Yabancı Takas Trendi
    let netFlowTrend: ForeignOwnership['netFlowTrend'] = 'NÖTR';
    if (item.foreignWeeklyChange >= 1.0) netFlowTrend = 'GÜÇLÜ GİRİŞ';
    else if (item.foreignWeeklyChange >= 0.3) netFlowTrend = 'GİRİŞ';
    else if (item.foreignWeeklyChange <= -0.8) netFlowTrend = 'GÜÇLÜ ÇIKIŞ';
    else if (item.foreignWeeklyChange <= -0.2) netFlowTrend = 'ÇIKIŞ';

    const foreignOwnership: ForeignOwnership = {
      currentRatio: item.foreignRatio,
      weeklyChange: item.foreignWeeklyChange,
      monthlyChange: +(item.foreignWeeklyChange * 2.4).toFixed(2),
      netFlowTrend,
      topCustodyBrokers: ['Citibank Yabancı', 'Deutsche Bank', 'QNB Finans'],
    };

    const technical = {
      rsi: item.rsi,
      macd: {
        macd: +(item.price * 0.015).toFixed(2),
        signal: +(item.price * 0.011).toFixed(2),
        histogram: +(item.price * 0.004).toFixed(2),
        bullishCross: item.rsi > 52,
      },
      movingAverages: {
        sma20: +(item.price * 0.97).toFixed(2),
        sma50: +(item.price * 0.94).toFixed(2),
        sma200: +(item.price * 0.88).toFixed(2),
        priceAboveSma20: item.trend !== 'DÜŞÜŞ',
        priceAboveSma50: item.trend !== 'DÜŞÜŞ',
        priceAboveSma200: item.trend !== 'DÜŞÜŞ',
        goldenCross: item.trend !== 'DÜŞÜŞ',
      },
      bollinger: {
        upper: +(item.price * 1.08).toFixed(2),
        middle: item.price,
        lower: +(item.price * 0.92).toFixed(2),
        bandwidth: 0.14,
        squeeze: item.trend === 'YATAY / TEST',
      },
      foreignOwnership,
      priceAction: {
        trend: item.trend,
        pattern: item.pattern,
        supportLevel,
        resistanceLevel,
        stopLossLevel,
        riskRewardRatio: +(Math.abs((item.targetPrice - item.price) / (item.price - stopLossLevel))).toFixed(1),
        nearKeySupport: isNearSupport,
        breakoutConfirmed: isBreakout,
        notes: `${item.pattern}. Destek: ${supportLevel} TL, Direnç: ${resistanceLevel} TL.`,
      },
    };

    const fundamental = {
      pe: item.pe,
      pb: item.pb,
      evEbitda: item.evEbitda,
      roe: item.roe,
      netDebtEbitda: item.sector === 'Bankacılık' ? 0 : 0.8,
      netProfitMargin: +(item.roe * 0.5).toFixed(1),
      revenueGrowthYoY: +(item.roe * 1.1).toFixed(1),
      dividendYield: item.pe < 8 ? 4.5 : item.pe < 12 ? 2.8 : 1.2,
      sectorPeAvg,
      valuationDiscount,
    };

    const analysts = {
      consensusTarget: item.targetPrice,
      currentPrice: item.price,
      upsidePotential,
      recommendations: {
        strongBuy: item.rsi > 60 ? 6 : 3,
        buy: 5,
        hold: item.rsi < 50 ? 4 : 1,
        sell: 0,
      },
      reports: [
        {
          broker: 'İş Yatırım',
          targetPrice: +(item.targetPrice * 1.03).toFixed(2),
          recommendation: 'AL' as const,
          date: '2026-09-18',
          upside: +(upsidePotential * 1.03).toFixed(1),
        },
        {
          broker: 'Garanti BBVA',
          targetPrice: +(item.targetPrice * 0.98).toFixed(2),
          recommendation: 'AL' as const,
          date: '2026-09-10',
          upside: +(upsidePotential * 0.98).toFixed(1),
        },
      ],
    };

    const kapCategory: KAPCategory = item.recentKAPCategory || (item.kapSentiment >= 70 ? 'YENİ PROJE & YATIRIM' : 'YENİ İŞ İLİŞKİSİ');
    const scoreBonus = kapCategory === 'PAY GERİ ALIMI' ? 25 : kapCategory === 'SERMAYE TAVANI ARTIRIMI' ? 20 : 15;

    const sentiment = {
      kapSentimentScore: item.kapSentiment,
      kapPositiveCount: item.kapSentiment > 40 ? 4 : 2,
      kapNegativeCount: item.kapSentiment < 20 ? 1 : 0,
      recentKAPNews: [
        {
          id: `${item.symbol.toLowerCase()}-kap-1`,
          date: '2026-09-24',
          title: item.recentKAPTitle || `${item.name} Operasyonel & Finansal Gelişmeler`,
          category: kapCategory,
          impact: item.recentKAPImpact || (item.kapSentiment >= 40 ? 'POZİTİF' : 'NÖTR'),
          financialImpactSummary: `${item.symbol} için bildirilen ${kapCategory.toLowerCase()} piyasada olumlu karşılanmaktadır.`,
          scoreBonus,
        },
      ],
      socialVolume: item.socialVolume,
      socialSentimentScore: Math.min(95, Math.max(35, Math.round((item.kapSentiment + 100) / 2.2))),
      socialTrend: item.socialVolume > 15000 ? ('PATLAMA' as const) : item.socialVolume > 8000 ? ('YÜKSEK' as const) : ('NORMAL' as const),
      communityPerception: `${item.symbol}, yabancı takasındaki ${netFlowTrend.toLowerCase()} ve ${kapCategory.toLowerCase()} ile dikkat çekiyor.`,
    };

    const score = evaluateBISTStock(
      item.symbol,
      item.price,
      technical,
      fundamental,
      analysts,
      sentiment,
      undefined, // weights — default kullan
      item.high52w,
      item.low52w,
    );

    return {
      symbol: item.symbol,
      name: item.name,
      sector: item.sector,
      indexCategory,
      currentPrice: item.price,
      changePercent: item.change,
      high52w: item.high52w,
      low52w: item.low52w,
      volume24h: item.volume * 1000000,
      marketCap: item.marketCap,
      technical,
      fundamental,
      analysts,
      sentiment,
      score,
    };
  });
}
